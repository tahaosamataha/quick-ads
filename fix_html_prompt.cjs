const fs = require('fs');
let code = fs.readFileSync('src/services/ai.ts', 'utf8');

const regex = /- الرجاء إطلاق العنان لإبداعك وتصميم صفحات HTML بهياكل و Layouts مختلفة ومبتكرة بالكامل، بدون الالتزام بأي قوالب أو تنسيقات ثابتة \(حرية مطلقة للذكاء الاصطناعي في التصميم\)\./;

const replacement = `- الرجاء إطلاق العنان لإبداعك وتصميم صفحات HTML بهياكل و Layouts مختلفة ومبتكرة بالكامل، بدون الالتزام بأي قوالب أو تنسيقات ثابتة (حرية مطلقة للذكاء الاصطناعي في التصميم). 
- تنبيه صارم جدًا (CRITICAL INSTRUCTION): لا تقم أبدًا بإعادة استخدام أو تكرار نفس الهيكل (Layout) أو التصميم (Design) الذي قمت بتوليده في الرسائل السابقة في هذا السجل (History). حتى لو قام المستخدم بالإعجاب (Like) بتصميم سابق، يجب عليك في كل مرة يتم استدعائك فيها لتوليد صفحة HTML أن تقوم بابتكار تصميم جديد كليًا، بألوان جديدة، ترتيب مختلف للأقسام، وأفكار بصرية غير مكررة نهائيًا. التنوع والتجديد المستمر هو الأهم.`;

code = code.replace(regex, replacement);
fs.writeFileSync('src/services/ai.ts', code);
